/*! RMB AI Chatbot widget (prototype). One script tag, no dependencies, Shadow DOM isolated.
 *
 *   <script src="https://HOST/widget.js" data-api="https://HOST/api/v1" data-lang="en"
 *           data-title="RMB Assistant" data-accent="#1f3864"></script>
 *
 * Works on any page (including TYPO3). All model output is inserted with textContent, never innerHTML.
 */
(function () {
  "use strict";
  if (window.__rmbChatbotLoaded) return;
  window.__rmbChatbotLoaded = true;

  var script = document.currentScript;
  var scriptOrigin = script && script.src ? new URL(script.src, location.href).origin : location.origin;
  var CFG = {
    api: ((script && script.dataset.api) || scriptOrigin + "/api/v1").replace(/\/$/, ""),
    lang: (script && script.dataset.lang) || "en",
    title: (script && script.dataset.title) || "RMB Assistant",
    accent: (script && script.dataset.accent) || "#1f3864",
  };
  if (!/^#[0-9a-fA-F]{3,8}$/.test(CFG.accent)) CFG.accent = "#1f3864";

  var WELCOME =
    "Hello, I am the RMB information assistant (prototype). Ask me about licensing, minerals, petroleum and gas, or mining safety. " +
    "I answer from RMB documents and show my sources. I can also log a complaint, a report or a request for RMB staff. This demo works in English only.";
  var NOTICE = "Prototype only, not an official RMB application. Contacts, emergency numbers, routing and response times are placeholders. Case references are generated by this demonstration system.";

  var CSS =
    ":host{all:initial}*{box-sizing:border-box}" +
    ".wrap{all:initial;position:fixed;right:20px;bottom:20px;z-index:2147483000;font:15px/1.45 system-ui,'Segoe UI',Arial,sans-serif;color:#1b2430}" +
    ".launch{display:flex;align-items:center;gap:8px;background:var(--a);color:#fff;border:0;border-radius:28px;padding:12px 18px;font:inherit;font-weight:600;cursor:pointer;box-shadow:0 4px 14px rgba(0,0,0,.25)}" +
    ".launch:focus-visible,button:focus-visible,input:focus-visible,summary:focus-visible{outline:3px solid #f5a623;outline-offset:2px}" +
    ".panel{display:none;flex-direction:column;width:380px;max-width:calc(100vw - 24px);height:560px;max-height:calc(100vh - 40px);background:#fff;border-radius:12px;box-shadow:0 8px 30px rgba(0,0,0,.3);overflow:hidden}" +
    ".open .panel{display:flex}.open .launch{display:none}" +
    ".head{background:var(--a);color:#fff;padding:12px 14px;display:flex;align-items:center;justify-content:space-between;font-weight:600}" +
    ".head button{background:none;border:0;color:#fff;font-size:22px;line-height:1;cursor:pointer;padding:2px 8px}" +
    ".notice{background:#fff4ce;border-bottom:1px solid #e0c36a;font-size:12px;padding:6px 12px}" +
    ".log{flex:1;overflow-y:auto;padding:12px;background:#f4f6f9;display:flex;flex-direction:column;gap:10px}" +
    ".msg{max-width:92%;padding:9px 12px;border-radius:12px;word-wrap:break-word}.msg p{margin:0 0 6px}.msg p:last-child{margin:0}" +
    ".bot{background:#fff;border:1px solid #d7dde6;align-self:flex-start}.user{background:var(--a);color:#fff;align-self:flex-end}" +
    ".disc{margin-top:8px;font-size:12px;font-style:italic;color:#4a5565;border-left:3px solid #9aa7ba;padding-left:8px}" +
    "details{margin-top:8px;font-size:13px}summary{cursor:pointer;font-weight:600;color:var(--a)}" +
    "details ol{margin:6px 0 0;padding-left:20px}details li{margin-bottom:6px}.snip{color:#4a5565;font-size:12px}" +
    "a{color:var(--a)}.case{margin-top:8px;border:2px solid #2e7d32;background:#e8f5e9;border-radius:8px;padding:8px 10px}" +
    ".case b{font-size:17px;letter-spacing:.5px}.case button{margin-left:8px;font-size:12px;padding:2px 8px;cursor:pointer}" +
    ".emerg{margin-top:8px;border:2px solid #b00020;background:#fdecea;border-radius:8px;padding:8px 10px}" +
    ".emerg h3{margin:0 0 6px;font-size:15px;color:#b00020}.emerg ul{list-style:none;margin:0;padding:0}.emerg li{margin:4px 0;font-size:16px}" +
    ".ph{font-size:11px;color:#6b7280}" +
    ".qr{display:flex;flex-wrap:wrap;gap:6px;padding:0 12px 8px;background:#f4f6f9}" +
    ".qr button{border:1px solid var(--a);background:#fff;color:var(--a);border-radius:16px;padding:5px 12px;font:inherit;font-size:13px;cursor:pointer}" +
    ".qr button:hover{background:var(--a);color:#fff}" +
    "form{display:flex;gap:8px;padding:10px;border-top:1px solid #d7dde6;background:#fff}" +
    "input{flex:1;border:1px solid #9aa7ba;border-radius:8px;padding:9px 10px;font:inherit;min-width:0}" +
    "form button{background:var(--a);color:#fff;border:0;border-radius:8px;padding:0 14px;font:inherit;font-weight:600;cursor:pointer}" +
    "form button:disabled,input:disabled{opacity:.6;cursor:not-allowed}" +
    ".dots span{display:inline-block;width:6px;height:6px;margin:0 2px;border-radius:50%;background:#9aa7ba;animation:b 1s infinite}" +
    ".dots span:nth-child(2){animation-delay:.15s}.dots span:nth-child(3){animation-delay:.3s}@keyframes b{50%{opacity:.25}}" +
    ".foot{font-size:11px;color:#6b7280;padding:0 12px 8px;background:#fff}" +
    "@media (max-width:480px){.wrap{right:8px;bottom:8px}.panel{width:calc(100vw - 16px);height:calc(100vh - 16px);max-height:none}}";

  function el(tag, props, children) {
    var n = document.createElement(tag);
    if (props) for (var k in props) {
      if (k === "text") n.textContent = props[k];
      else if (k === "class") n.className = props[k];
      else n.setAttribute(k, props[k]);
    }
    (children || []).forEach(function (c) { if (c) n.appendChild(c); });
    return n;
  }

  var sessionId = null;
  try { sessionId = sessionStorage.getItem("rmb_chat_sid"); } catch (e) { /* storage may be blocked */ }
  function saveSid(id) { sessionId = id; try { sessionStorage.setItem("rmb_chat_sid", id); } catch (e) { /* ignore */ } }

  var host = el("div");
  host.id = "rmb-chatbot-host";
  var root = host.attachShadow({ mode: "open" });
  root.appendChild(el("style", { text: CSS }));

  var wrap = el("div", { class: "wrap" });
  wrap.style.setProperty("--a", CFG.accent);
  var launch = el("button", { class: "launch", type: "button", "aria-label": "Open chat: " + CFG.title }, [el("span", { text: "\u{1F4AC}" }), el("span", { text: "Ask RMB" })]);
  var closeBtn = el("button", { type: "button", "aria-label": "Close chat", text: "\u00D7" });
  var log = el("div", { class: "log", role: "log", "aria-live": "polite", "aria-label": "Conversation" });
  var qr = el("div", { class: "qr" });
  var input = el("input", { type: "text", maxlength: "1000", "aria-label": "Type your question", placeholder: "Type your question...", autocomplete: "off" });
  var send = el("button", { type: "submit", text: "Send" });
  var form = el("form", null, [input, send]);
  var panel = el("section", { class: "panel", role: "dialog", "aria-label": CFG.title }, [
    el("div", { class: "head" }, [el("span", { text: CFG.title }), closeBtn]),
    el("div", { class: "notice", text: NOTICE }),
    log, qr, form,
    el("div", { class: "foot", text: "Do not share sensitive personal data unless I ask for it to create a case." }),
  ]);
  wrap.appendChild(launch);
  wrap.appendChild(panel);
  root.appendChild(wrap);

  function scroll() { log.scrollTop = log.scrollHeight; }
  function paragraphs(text) {
    return String(text).split(/\n{2,}/).map(function (p) { return el("p", { text: p }); });
  }
  function safeUrl(u) { return /^https?:\/\//i.test(u || "") && !/example\.invalid/.test(u) ? u : null; }

  function addUser(text) {
    log.appendChild(el("div", { class: "msg user", text: text }));
    scroll();
  }

  function addBot(d) {
    var kids = paragraphs(d.answer);
    if (d.action === "emergency") {
      var ul = el("ul");
      (d.emergency_contacts || []).forEach(function (c) {
        var num = String(c.number).replace(/[^+\d]/g, "");
        var li = el("li", null, [el("strong", { text: c.name + ": " }), el("a", { href: "tel:" + num, text: c.number })]);
        if (c.placeholder) li.appendChild(el("span", { class: "ph", text: " (placeholder, to be confirmed)" }));
        ul.appendChild(li);
      });
      kids.push(el("div", { class: "emerg", role: "alert" }, [el("h3", { text: "Emergency contacts" }), ul]));
    }
    if (d.sources && d.sources.length) {
      var ol = el("ol");
      d.sources.forEach(function (s) {
        var label = s.title + (s.section ? ", " + s.section : "") + (s.page ? " (page " + s.page + ")" : "");
        var u = safeUrl(s.url);
        var li = el("li", null, [u ? el("a", { href: u, target: "_blank", rel: "noopener noreferrer", text: label }) : el("span", { text: label })]);
        if (s.snippet) li.appendChild(el("div", { class: "snip", text: s.snippet }));
        ol.appendChild(li);
      });
      kids.push(el("details", null, [el("summary", { text: "Sources (" + d.sources.length + ")" }), ol]));
    }
    if (d.disclaimer) kids.push(el("div", { class: "disc", text: d.disclaimer }));
    if (d.case_reference) {
      var copy = el("button", { type: "button", text: "Copy" });
      copy.addEventListener("click", function () {
        try { navigator.clipboard.writeText(d.case_reference); copy.textContent = "Copied"; } catch (e) { copy.textContent = "Select and copy"; }
      });
      kids.push(el("div", { class: "case" }, [el("div", { text: "Case reference" }), el("b", { text: d.case_reference }), copy]));
    }
    log.appendChild(el("div", { class: "msg bot" }, kids));
    qr.textContent = "";
    (d.quick_replies || []).forEach(function (q) {
      var b = el("button", { type: "button", text: q });
      b.addEventListener("click", function () { ask(q); });
      qr.appendChild(b);
    });
    scroll();
  }

  function busy(on) { input.disabled = on; send.disabled = on; }

  function ask(text) {
    text = String(text || "").trim();
    if (!text) return;
    addUser(text);
    qr.textContent = "";
    input.value = "";
    busy(true);
    var typing = el("div", { class: "msg bot dots", "aria-label": "Assistant is typing" }, [el("span"), el("span"), el("span")]);
    log.appendChild(typing);
    scroll();
    var ctl = new AbortController();
    var timer = setTimeout(function () { ctl.abort(); }, 30000);
    fetch(CFG.api + "/chat", {
      method: "POST", headers: { "Content-Type": "application/json" }, signal: ctl.signal,
      body: JSON.stringify({ session_id: sessionId, message: text, language: CFG.lang }),
    })
      .then(function (r) {
        if (r.status === 429) throw new Error("rate");
        if (!r.ok) throw new Error("http");
        return r.json();
      })
      .then(function (d) { saveSid(d.session_id); typing.remove(); addBot(d); })
      .catch(function (e) {
        typing.remove();
        addBot({ answer: e.message === "rate" ? "You are sending messages very quickly. Please wait a moment and try again."
          : "Sorry, I cannot reach the assistant right now. Please try again in a few minutes." });
      })
      .finally(function () { clearTimeout(timer); busy(false); input.focus(); });
  }

  function open() { wrap.classList.add("open"); input.focus(); }
  function close() { wrap.classList.remove("open"); launch.focus(); }
  launch.addEventListener("click", open);
  closeBtn.addEventListener("click", close);
  panel.addEventListener("keydown", function (e) { if (e.key === "Escape") close(); });
  form.addEventListener("submit", function (e) { e.preventDefault(); ask(input.value); });

  log.appendChild(el("div", { class: "msg bot" }, paragraphs(WELCOME)));

  function mount() { document.body.appendChild(host); }
  if (document.body) mount(); else document.addEventListener("DOMContentLoaded", mount);

  window.RMBChatbot = { open: open, close: close, ask: ask };
})();
